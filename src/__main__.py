import contextlib, io, traceback, os, time, httpx, datetime, re
from dotenv import load_dotenv
from dataclasses import dataclass
from pydantic import Field

load_dotenv()


@dataclass
class LLMResponse:
    input_tokens: int
    output_tokens: int
    request_time_ms: float
    api_url: str
    model_name: str
    llm_output: str = Field(
        default="",
        description="Raw text generated by the LLM before code extraction",
    )


def generate(
    messages: list[dict], stop: list[str] | None = None
) -> LLMResponse:
    """
    Calls LLM and returns the generated text and its metrics.
    """

    start_time = time.perf_counter()
    response = httpx.request(
        "POST",
        f"{os.environ['BASE_URL']}/chat/completions",
        headers={"Authorization": f"Bearer {os.environ['GROQ_API_KEY']}"},
        json={
            "model": os.environ["MODEL"],
            "messages": messages,
            "stop": stop,
        },
        timeout=30.0,
    )
    request_time_ms = (time.perf_counter() - start_time) * 1000
    response.raise_for_status()
    data = response.json()
    return LLMResponse(
        input_tokens=data["usage"]["prompt_tokens"],
        output_tokens=data["usage"]["completion_tokens"],
        request_time_ms=request_time_ms,
        api_url=f"{os.environ['BASE_URL']}",
        model_name=data["model"],
        llm_output=data["choices"][0]["message"]["content"],
    )


def extract_code(text: str) -> str | None:
    """Return the first Python code block before <end_code>, or None."""
    text = text.split("<end_code>")[0]
    parts = text.split("```python\n", 1)
    if len(parts) < 2:
        return None
    return parts[1].split("```")[0]


class FinalAnswer(BaseException):
    def __init__(self, value: str) -> None:
        self.value = value


def final_answer(value: str) -> None:
    raise FinalAnswer(value)


def lancer(code: str, namespace: dict) -> str:
    boite = io.StringIO()
    try:
        with contextlib.redirect_stdout(boite):
            exec(code, namespace)
    except Exception:
        boite.write(traceback.format_exc())
    return boite.getvalue()


SYSTEM_PROMPT = """You solve tasks by writing Python code.
Reply with a short thought, then ONE code block:
```python
# your code
```
<end_code>
Your code is executed and you receive what it printed as an observation.
Use print() to see values. When you have the answer, call final_answer(answer).
"""


def run_agent(task: str, max_iterations: int = 5):
    namespace = {"final_answer": final_answer}
    messages = [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": task},
    ]
    for i in range(1, max_iterations + 1):
        try:
            llm_response = generate(messages)
        except httpx.HTTPStatusError as e:
            print(e)
        code = extract_code(llm_response.llm_output)
        if code is None:
            observation = (
                "No valid code block was found in the model’s response"
            )
        else:
            try:
                observation = lancer(code, namespace)
            except FinalAnswer as f:
                return f.value
        messages.append(
            {"role": "user", "content": f"'observation': {observation}"}
        )
    return None
